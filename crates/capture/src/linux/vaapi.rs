/// The sequence-level settings of a running pipeline.
enum Sequence {
    /// H.264 with its macroblock geometry.
    H264(H264Settings),
    /// H.265 with its coding-tree geometry.
    Hevc(HevcSettings),
}

impl Sequence {
    /// The width of the surface the driver codes, padded up to the codec's block size.
    const fn surface_width(&self) -> u32 {
        match self {
            Self::H264(settings) => settings.surface_width(),
            Self::Hevc(settings) => settings.surface_width,
        }
    }

    /// The height of the surface the driver codes.
    const fn surface_height(&self) -> u32 {
        match self {
            Self::H264(settings) => settings.surface_height(),
            Self::Hevc(settings) => settings.surface_height,
        }
    }

    /// Every parameter set, in decode order, as one Annex B blob: `SPS || PPS` for H.264,
    /// `VPS || SPS || PPS` for H.265. It goes in front of the first slice of each IDR.
    fn parameter_sets(&self) -> Vec<u8> {
        match self {
            Self::H264(settings) => {
                let mut sets = settings.write_sps();
                sets.extend_from_slice(&settings.write_pps());
                sets
            }
            Self::Hevc(settings) => {
                let mut sets = settings.write_vps();
                sets.extend_from_slice(&settings.write_sps());
                sets.extend_from_slice(&settings.write_pps());
                sets
            }
        }
    }
}

/// One live VAAPI encoding pipeline.
///
/// Every method must run on the thread that built the encoder: libva makes no promise about
/// moving a display between threads, so the capture thread owns this value for its whole life.
pub(crate) struct Encoder {
    /// The render node the display was created from; libva takes its own reference, but the
    /// descriptor has to stay open for as long as the display lives.
    _drm: OwnedFd,
    display: VaDisplay,
    config: VaConfigId,
    context: VaContextId,
    /// The two surfaces that alternate between "current picture" and "reference".
    surfaces: [VaSurfaceId; 2],
    /// Whether `surfaces` holds live handles, as opposed to a partly created set.
    surfaces_created: bool,
    coded_buffer: VaBufferId,
    /// Sequence parameters: created once, referenced by every picture.
    sequence_parameters: VaBufferId,
    /// Rate control and frame rate parameters: created once, referenced by every picture.
    misc_parameters: [VaBufferId; 2],
    /// The packed parameter sets, rebuilt only when the pipeline is rebuilt.
    parameter_sets: Vec<u8>,
    /// The buffer list of the frame being rendered, kept to avoid a per-frame allocation.
    render_buffers: Vec<VaBufferId>,
    /// The staging image frames are uploaded into, created on first use.
    image: Option<VaImage>,
    sequence: Sequence,
    /// Picture width in pixels, as requested.
    width: u32,
    /// Picture height in pixels, as requested.
    height: u32,
    /// GOP length in frames.
    gop: u32,
    /// Frames encoded so far, which is also the source of `frame_num` and the picture order
    /// count.
    frame_index: u64,
    /// `idr_pic_id` of the most recent IDR (H.264 only).
    idr_pic_id: u16,
}

impl Encoder {
    /// Builds an encoder on one DRM render node.
    ///
    /// The node is opened here and kept open for the encoder's life; libva takes its own
    /// reference to the descriptor, and a display must not outlive the node it came from.
    ///
    /// Fails with [`CaptureError::PermissionDenied`] when the node exists but the process may
    /// not open it, and with [`CaptureError::UnsupportedParameters`] when the driver has no
    /// encode entry point for the codec.
    pub(crate) fn new(
        node: &Path,
        width: u32,
        height: u32,
        fps: u32,
        codec: Codec,
        bitrate_kbps: u32,
    ) -> Result<Self, CaptureError> {
        if width == 0 || height == 0 || fps == 0 || bitrate_kbps == 0 {
            return Err(CaptureError::UnsupportedParameters);
        }
        let drm = open_render_node(node)?;
        let display = display_from_drm(drm.as_raw_fd())?;
        match Self::build(drm, display, width, height, fps, codec, bitrate_kbps) {
            Ok(encoder) => Ok(encoder),
            Err(error) => {
                // SAFETY: `display` came from `display_from_drm` and no half-built encoder
                // escaped, so nothing else holds a reference to it.
                unsafe { vaTerminate(display) };
                Err(error)
            }
        }
    }

    /// The part of construction that can fail once the display exists.
    fn build(
        drm: OwnedFd,
        display: VaDisplay,
        width: u32,
        height: u32,
        fps: u32,
        codec: Codec,
        bitrate_kbps: u32,
    ) -> Result<Self, CaptureError> {
        let (h264_profile, sequence) = match codec {
            Codec::H264 => {
                let profile = supported_h264_profile(display)?;
                (profile, Sequence::H264(H264Settings::new(width, height, fps, profile)))
            }
            Codec::Hevc => {
                if !supports_encode(display, VAProfileHEVCMain) {
                    return Err(CaptureError::UnsupportedParameters);
                }
                // HEVC declares per-coding-unit QP deltas in both the PPS and the picture
                // parameters; rate control uses them to hold the bitrate.
                (
                    H264Profile::High,
                    Sequence::Hevc(HevcSettings::new(width, height, fps, true)),
                )
            }
        };
        let profile = codec.profile(h264_profile);
        tracing::info!(
            ?codec,
            profile,
            width,
            height,
            fps,
            bitrate_kbps,
            "configuring the VAAPI encoder"
        );

        let parameter_sets = sequence.parameter_sets();
        let mut encoder = Self {
            _drm: drm,
            display,
            config: VA_INVALID_ID,
            context: VA_INVALID_ID,
            surfaces: [VA_INVALID_ID; 2],
            surfaces_created: false,
            coded_buffer: VA_INVALID_ID,
            sequence_parameters: VA_INVALID_ID,
            misc_parameters: [VA_INVALID_ID; 2],
            parameter_sets,
            render_buffers: Vec::with_capacity(8),
            image: None,
            sequence,
            width,
            height,
            gop: fps.saturating_mul(GOP_SECONDS).max(1),
            frame_index: 0,
            idr_pic_id: 0,
        };

        encoder.create_config(profile)?;
        encoder.create_surfaces()?;
        encoder.create_context()?;
        encoder.create_coded_buffer()?;
        encoder.create_sequence_parameters(bitrate_kbps)?;
        encoder.create_misc_parameters(bitrate_kbps, fps)?;
        Ok(encoder)
    }

    /// Creates the encode config and checks what it can insert into the stream.
    ///
    /// The rate-control attribute is what turns the driver's bitrate target into a constant
    /// one, which is what the protocol's `bitrate_kbps` means. A driver that refuses that
    /// combination is retried without the attribute, because several drivers choose a
    /// rate-control mode themselves and only accept it unset.
    fn create_config(&mut self, profile: i32) -> Result<(), CaptureError> {
        let mut attribute = VaConfigAttrib {
            kind: VAConfigAttribRateControl,
            value: VA_RC_CBR,
        };
        // SAFETY: the display is live, the attribute is valid for one element, and the config
        // id is written on success.
        let status = unsafe {
            vaCreateConfig(
                self.display,
                profile,
                VAEntrypointEncSlice,
                &mut attribute,
                1,
                &mut self.config,
            )
        };
        if status != VA_STATUS_SUCCESS {
            tracing::debug!(
                profile,
                error = %va_error_string(status),
                "creating a CBR encode config failed; retrying without a rate-control attribute"
            );
            // SAFETY: as above, with no attributes to check.
            let status = unsafe {
                vaCreateConfig(
                    self.display,
                    profile,
                    VAEntrypointEncSlice,
                    ptr::null_mut(),
                    0,
                    &mut self.config,
                )
            };
            if status != VA_STATUS_SUCCESS {
                return Err(va_error("vaCreateConfig", status));
            }
        }

        let mut headers = VaConfigAttrib {
            kind: VAConfigAttribEncPackedHeaders,
            value: 0,
        };
        // SAFETY: one valid attribute pointer, as the API expects.
        let status = unsafe {
            vaGetConfigAttributes(self.display, profile, VAEntrypointEncSlice, &mut headers, 1)
        };
        if status != VA_STATUS_SUCCESS {
            return Err(va_error("vaGetConfigAttributes", status));
        }
        if headers.value == VA_ATTRIB_NOT_SUPPORTED
            || headers.value & VA_ENC_PACKED_HEADER_SEQUENCE == 0
        {
            // The parameter sets have to travel with the stream — the server has no other way
            // to learn them — so a driver that cannot splice them in is unusable.
            return Err(CaptureError::Os(format!(
                "the VAAPI driver cannot insert packed sequence headers (reports {:#x})",
                headers.value
            )));
        }
        Ok(())
    }

    /// Creates the two alternating NV12 surfaces.
    fn create_surfaces(&mut self) -> Result<(), CaptureError> {
        let mut attribute = VaSurfaceAttrib {
            kind: VASurfaceAttribPixelFormat,
            flags: VA_SURFACE_ATTRIB_SETTABLE,
            value: VaGenericValue {
                kind: VAGenericValueTypeInteger,
                value: u64::from(VA_FOURCC_NV12),
            },
        };
        let width = self.sequence.surface_width();
        let height = self.sequence.surface_height();
        // SAFETY: the display is live, `surfaces` is a valid two-element array, and the
        // attribute is one valid, settable entry.
        let status = unsafe {
            vaCreateSurfaces(
                self.display,
                VA_RT_FORMAT_YUV420,
                width,
                height,
                self.surfaces.as_mut_ptr(),
                self.surfaces.len() as u32,
                &mut attribute,
                1,
            )
        };
        if status != VA_STATUS_SUCCESS {
            return Err(va_error("vaCreateSurfaces", status));
        }
        self.surfaces_created = true;
        tracing::debug!(width, height, "created two NV12 encode surfaces");
        Ok(())
    }

    /// Creates the encode context over the surfaces just made.
    fn create_context(&mut self) -> Result<(), CaptureError> {
        let width = i32::try_from(self.sequence.surface_width())
            .map_err(|_| CaptureError::UnsupportedParameters)?;
        let height = i32::try_from(self.sequence.surface_height())
            .map_err(|_| CaptureError::UnsupportedParameters)?;
        // SAFETY: display, config and surfaces are live and of the sizes passed.
        let status = unsafe {
            vaCreateContext(
                self.display,
                self.config,
                width,
                height,
                0,
                self.surfaces.as_mut_ptr(),
                self.surfaces.len() as i32,
                &mut self.context,
            )
        };
        if status != VA_STATUS_SUCCESS {
            return Err(va_error("vaCreateContext", status));
        }
        Ok(())
    }

    /// Creates the one coded buffer every frame is compressed into.
    ///
    /// It is sized as FFmpeg sizes it — an uncompressed frame plus 64 KiB of headers — and
    /// reused, which is safe because each frame is synchronised and drained before the next
    /// one renders.
    fn create_coded_buffer(&mut self) -> Result<(), CaptureError> {
        let size = self
            .sequence
            .surface_width()
            .saturating_mul(self.sequence.surface_height())
            .saturating_mul(3)
            .saturating_add(CODED_BUFFER_SLACK);
        self.coded_buffer = create_buffer(
            self.display,
            self.context,
            VAEncCodedBufferType,
            size,
            ptr::null_mut(),
        )?;
        Ok(())
    }

    /// Creates the sequence parameter buffer, which every picture references.
    fn create_sequence_parameters(&mut self, bitrate_kbps: u32) -> Result<(), CaptureError> {
        let bits_per_second = bitrate_kbps.saturating_mul(1000);
        match self.sequence {
            Sequence::H264(settings) => {
                let mut sequence =
                    h264_sequence_parameters(&settings, bits_per_second, self.gop);
                self.sequence_parameters = create_buffer(
                    self.display,
                    self.context,
                    VAEncSequenceParameterBufferType,
                    u32::try_from(size_of::<VaEncSequenceParameterH264>())
                        .map_err(|_| CaptureError::UnsupportedParameters)?,
                    ptr::from_mut(&mut sequence).cast::<c_void>(),
                )?;
            }
            Sequence::Hevc(settings) => {
                let mut sequence = hevc_sequence_parameters(&settings, bits_per_second, self.gop);
                self.sequence_parameters = create_buffer(
                    self.display,
                    self.context,
                    VAEncSequenceParameterBufferType,
                    u32::try_from(size_of::<VaEncSequenceParameterHevc>())
                        .map_err(|_| CaptureError::UnsupportedParameters)?,
                    ptr::from_mut(&mut sequence).cast::<c_void>(),
                )?;
            }
        }
        Ok(())
    }

    /// Creates the rate-control and frame-rate parameters, which every picture references.
    fn create_misc_parameters(&mut self, bitrate_kbps: u32, fps: u32) -> Result<(), CaptureError> {
        let mut rate_control = MiscRateControl {
            kind: VAEncMiscParameterTypeRateControl,
            rate_control: VaEncMiscParameterRateControl {
                bits_per_second: bitrate_kbps.saturating_mul(1000),
                // CBR means the target *is* the maximum; the driver ignores the percentage.
                target_percentage: 100,
                // The window the rate controller averages over, in milliseconds: one second,
                // as FFmpeg's CBR mode uses.
                window_size: 1000,
                initial_qp: 0,
                min_qp: 0,
                basic_unit_size: 0,
                rc_flags: 0,
                icq_quality_factor: 0,
                max_qp: 0,
                quality_factor: 0,
                target_frame_size: 0,
                reserved: [0; 4],
            },
        };
        self.misc_parameters[0] = create_buffer(
            self.display,
            self.context,
            VAEncMiscParameterBufferType,
            u32::try_from(size_of::<MiscRateControl>())
                .map_err(|_| CaptureError::UnsupportedParameters)?,
            ptr::from_mut(&mut rate_control).cast::<c_void>(),
        )?;

        let mut framerate = MiscFrameRate {
            kind: VAEncMiscParameterTypeFrameRate,
            frame_rate: VaEncMiscParameterFrameRate {
                // The API packs the frame rate as (denominator << 16) | numerator, which for a
                // whole number of frames per second is (1 << 16) | fps.
                framerate: (1 << 16) | (fps & 0xFFFF),
                framerate_flags: 0,
                reserved: [0; 4],
            },
        };
        self.misc_parameters[1] = create_buffer(
            self.display,
            self.context,
            VAEncMiscParameterBufferType,
            u32::try_from(size_of::<MiscFrameRate>())
                .map_err(|_| CaptureError::UnsupportedParameters)?,
            ptr::from_mut(&mut framerate).cast::<c_void>(),
        )?;
        Ok(())
    }

    /// Encodes one NV12 frame and appends the Annex B access unit to `out`.
    ///
    /// Returns whether the access unit is a keyframe, i.e. an IDR preceded by its parameter
    /// sets. The frame must be tightly packed NV12 of the requested size.
    pub(crate) fn encode(&mut self, frame: &[u8], out: &mut Vec<u8>) -> Result<bool, CaptureError> {
        let needed = (self.width as usize) * (self.height as usize) * 3 / 2;
        if frame.len() < needed {
            return Err(CaptureError::Os(format!(
                "encoder input is {} bytes, expected {needed} for a {}x{} NV12 frame",
                frame.len(),
                self.width,
                self.height
            )));
        }

        // The surfaces alternate; the one the previous frame reconstructed into is this
        // frame's reference.
        let current = (self.frame_index % 2) as usize;
        let surface = self.surfaces[current];
        let reference = if self.frame_index == 0 {
            VA_INVALID_ID
        } else {
            self.surfaces[1 - current]
        };
        let keyframe = self.frame_index % u64::from(self.gop) == 0;
        let frame_num = (self.frame_index % FRAME_NUM_MODULUS) as u32;
        let pic_order_cnt = frame_num as i32;

        self.upload(surface, frame)?;

        // Picture and slice parameters change per frame; everything else is shared.
        let mut buffer_count = 0;
        self.render_buffers.clear();
        self.render_buffers.push(self.sequence_parameters);
        self.render_buffers.push(self.misc_parameters[0]);
        self.render_buffers.push(self.misc_parameters[1]);

        let sequence = &self.sequence;
        let picture = match sequence {
            Sequence::H264(settings) => {
                let mut parameters = h264_picture_parameters(
                    settings,
                    surface,
                    reference,
                    frame_num,
                    pic_order_cnt,
                    self.coded_buffer,
                    keyframe,
                    self.idr_pic_id,
                );
                create_buffer(
                    self.display,
                    self.context,
                    VAEncPictureParameterBufferType,
                    u32::try_from(size_of::<VaEncPictureParameterH264>())
                        .map_err(|_| CaptureError::UnsupportedParameters)?,
                    ptr::from_mut(&mut parameters).cast::<c_void>(),
                )?
            }
            Sequence::Hevc(_) => {
                let mut parameters = hevc_picture_parameters(
                    surface,
                    reference,
                    pic_order_cnt,
                    self.coded_buffer,
                    keyframe,
                );
                create_buffer(
                    self.display,
                    self.context,
                    VAEncPictureParameterBufferType,
                    u32::try_from(size_of::<VaEncPictureParameterHevc>())
                        .map_err(|_| CaptureError::UnsupportedParameters)?,
                    ptr::from_mut(&mut parameters).cast::<c_void>(),
                )?
            }
        };
        self.render_buffers.push(picture);

        let slice = match sequence {
            Sequence::H264(settings) => {
                let mut parameters = h264_slice_parameters(
                    settings,
                    reference,
                    frame_num,
                    pic_order_cnt,
                    self.idr_pic_id,
                    keyframe,
                );
                create_buffer(
                    self.display,
                    self.context,
                    VAEncSliceParameterBufferType,
                    u32::try_from(size_of::<VaEncSliceParameterH264>())
                        .map_err(|_| CaptureError::UnsupportedParameters)?,
                    ptr::from_mut(&mut parameters).cast::<c_void>(),
                )?
            }
            Sequence::Hevc(settings) => {
                let mut parameters =
                    hevc_slice_parameters(settings, reference, pic_order_cnt, keyframe);
                create_buffer(
                    self.display,
                    self.context,
                    VAEncSliceParameterBufferType,
                    u32::try_from(size_of::<VaEncSliceParameterHevc>())
                        .map_err(|_| CaptureError::UnsupportedParameters)?,
                    ptr::from_mut(&mut parameters).cast::<c_void>(),
                )?
            }
        };
        self.render_buffers.push(slice);

        // The parameter sets ride in front of every IDR. They are what makes an access unit
        // decodable on its own, so a client that joins mid-stream can start there.
        let packed = if keyframe {
            let packed = self.create_parameter_set_buffers();
            match packed {
                Ok(packed) => Some(packed),
                Err(error) => {
                    self.release_frame_buffers(picture, slice);
                    return Err(error);
                }
            }
        } else {
            None
        };
        if let Some((header, data)) = packed {
            self.render_buffers.push(header);
            self.render_buffers.push(data);
        }
        buffer_count += self.render_buffers.len();

        let result = self
            .render(surface)
            .and_then(|()| self.read_coded_buffer(surface, keyframe, out));

        // The per-frame buffers are dead once the picture has been rendered and synchronised;
        // the sequence and misc parameters stay for the next frame.
        self.release_frame_buffers(picture, slice);
        let _ = buffer_count;

        result?;
        self.frame_index += 1;
        if keyframe {
            // Only IDR slices carry an `idr_pic_id`, and the H.264 spec wants successive IDRs
            // to differ so that a decoder can tell two IDRs with the same `frame_num` apart.
            self.idr_pic_id = self.idr_pic_id.wrapping_add(1);
        }
        Ok(keyframe)
    }

    /// Destroys the buffers that only this frame needed.
    fn release_frame_buffers(&self, picture: VaBufferId, slice: VaBufferId) {
        // The packed-header buffers are destroyed separately, by the caller that created them
        // through `create_parameter_set_buffers`; the render list is cleared here so a failure
        // in between cannot leave stale ids behind.
        for buffer in [picture, slice] {
            if !self.destroy_buffer(buffer) {
                tracing::warn!("a VAAPI parameter buffer could not be destroyed");
            }
        }
    }

    /// Creates the packed-header description and data buffers for the parameter sets.
    fn create_parameter_set_buffers(&self) -> Result<(VaBufferId, VaBufferId), CaptureError> {
        let mut header = header_parameter(self.parameter_sets.len());
        let parameter = create_buffer(
            self.display,
            self.context,
            VAEncPackedHeaderParameterBufferType,
            u32::try_from(size_of::<VaEncPackedHeaderParameter>())
                .map_err(|_| CaptureError::UnsupportedParameters)?,
            ptr::from_mut(&mut header).cast::<c_void>(),
        )?;
        let data = match create_buffer(
            self.display,
            self.context,
            VAEncPackedHeaderDataBufferType,
            u32::try_from(self.parameter_sets.len())
                .map_err(|_| CaptureError::UnsupportedParameters)?,
            self.parameter_sets.as_ptr().cast_mut().cast::<c_void>(),
        ) {
            Ok(data) => data,
            Err(error) => {
                self.destroy_buffer(parameter);
                return Err(error);
            }
        };
        tracing::debug!(
            bytes = self.parameter_sets.len(),
            "prefixed the IDR with its parameter sets"
        );
        Ok((parameter, data))
    }

    /// Copies a frame into the staging image and blits it into a surface.
    fn upload(&mut self, surface: VaSurfaceId, frame: &[u8]) -> Result<(), CaptureError> {
        if self.image.is_none() {
            self.image = Some(self.create_image()?);
        }
        let image = self.image.expect("the staging image was just created");
        {
            let mut mapping = self.map_buffer(image.buf, image.data_size as usize)?;
            let destination = mapping.as_mut_slice();
            match image.format.fourcc {
                VA_FOURCC_NV12 => write_nv12(
                    destination,
                    &image,
                    frame,
                    self.width as usize,
                    self.height as usize,
                )?,
                VA_FOURCC_I420 | VA_FOURCC_YV12 => write_i420(
                    destination,
                    &image,
                    frame,
                    self.width as usize,
                    self.height as usize,
                    image.format.fourcc == VA_FOURCC_YV12,
                )?,
                other => {
                    return Err(CaptureError::Os(format!(
                        "the VAAPI driver created a {other:#x} staging image, which this \
                         backend cannot fill"
                    )));
                }
            }
            // Unmapped before the driver reads it back.
        }

        // SAFETY: both handles are live and the rectangles are inside both image and surface.
        let status = unsafe {
            vaPutImage(
                self.display,
                surface,
                image.image_id,
                0,
                0,
                self.width,
                self.height,
                0,
                0,
                self.width,
                self.height,
            )
        };
        if status != VA_STATUS_SUCCESS {
            return Err(va_error("vaPutImage", status));
        }
        Ok(())
    }

    /// Creates the staging image the frames are copied into.
    fn create_image(&self) -> Result<VaImage, CaptureError> {
        let mut format = VaImageFormat {
            fourcc: VA_FOURCC_NV12,
            byte_order: VA_LSB_FIRST,
            bits_per_pixel: NV12_BITS_PER_PIXEL,
            ..VaImageFormat::default()
        };
        let mut image = VaImage::default();
        let width = i32::try_from(self.width).map_err(|_| CaptureError::UnsupportedParameters)?;
        let height =
            i32::try_from(self.height).map_err(|_| CaptureError::UnsupportedParameters)?;
        // SAFETY: the display is live and both the format and the image are written in place.
        let status =
            unsafe { vaCreateImage(self.display, &mut format, width, height, &mut image.image_id) };
        if status != VA_STATUS_SUCCESS {
            return Err(va_error("vaCreateImage", status));
        }
        // The driver may substitute a format it prefers, and the copy has to follow the layout
        // it actually reports rather than the one requested.
        image.format = format;
        tracing::debug!(
            fourcc = format!("{:#x}", image.format.fourcc),
            pitches = ?image.pitches,
            offsets = ?image.offsets,
            data_size = image.data_size,
            "created the VAAPI staging image"
        );
        Ok(image)
    }

    /// Renders one picture: begin, hand over the buffers, end.
    fn render(&mut self, surface: VaSurfaceId) -> Result<(), CaptureError> {
        // SAFETY: the context is live and `surface` is one of the context's surfaces.
        let status = unsafe { vaBeginPicture(self.display, self.context, surface) };
        if status != VA_STATUS_SUCCESS {
            return Err(va_error("vaBeginPicture", status));
        }
        // SAFETY: the render list is valid for its length and holds live buffers.
        let status = unsafe {
            vaRenderPicture(
                self.display,
                self.context,
                self.render_buffers.as_mut_ptr(),
                self.render_buffers.len() as i32,
            )
        };
        if status != VA_STATUS_SUCCESS {
            return Err(va_error("vaRenderPicture", status));
        }
        // SAFETY: a picture is in progress on this context.
        let status = unsafe { vaEndPicture(self.display, self.context) };
        if status != VA_STATUS_SUCCESS {
            return Err(va_error("vaEndPicture", status));
        }
        Ok(())
    }

    /// Waits for the encode to finish, then copies the bitstream out of the coded buffer.
    fn read_coded_buffer(
        &self,
        surface: VaSurfaceId,
        keyframe: bool,
        out: &mut Vec<u8>,
    ) -> Result<(), CaptureError> {
        // SAFETY: `surface` holds the picture that was just rendered.
        let status = unsafe { vaSyncSurface(self.display, surface) };
        if status != VA_STATUS_SUCCESS {
            return Err(va_error("vaSyncSurface", status));
        }

        let mapping = self.map_buffer(self.coded_buffer, 0)?;
        // SAFETY: a mapped coded buffer points at a `VACodedBufferSegment` list that the
        // driver keeps valid until the buffer is unmapped.
        let mut segment = unsafe { &*mapping.as_ptr().cast::<VaCodedBufferSegment>() };
        loop {
            if segment.status & VA_CODED_BUF_STATUS_BAD_BITSTREAM != 0 {
                tracing::warn!(keyframe, "the VAAPI driver reported a damaged bitstream");
            }
            if segment.size > 0 && !segment.buf.is_null() {
                // SAFETY: the driver filled `size` bytes at `buf` for this segment.
                let bytes =
                    unsafe { std::slice::from_raw_parts(segment.buf, segment.size as usize) };
                out.extend_from_slice(bytes);
            }
            if segment.next.is_null() {
                break;
            }
            // SAFETY: the list is terminated by the null `next` checked above.
            segment = unsafe { &*segment.next };
        }
        Ok(())
    }

    /// Maps one driver buffer for CPU access.
    ///
    /// `len` is what the caller may touch; a coded buffer describes its contents itself, so
    /// it is mapped with a zero length and reached through the driver's own segment list.
    fn map_buffer(&self, buffer: VaBufferId, len: usize) -> Result<VaMapping, CaptureError> {
        let mut pointer: *mut c_void = ptr::null_mut();
        // SAFETY: the buffer is live and belongs to this display.
        let status = unsafe { vaMapBuffer(self.display, buffer, &mut pointer) };
        if status != VA_STATUS_SUCCESS {
            return Err(va_error("vaMapBuffer", status));
        }
        let Some(pointer) = ptr::NonNull::new(pointer.cast::<u8>()) else {
            // The driver still counted a reference, so it has to be given back.
            // SAFETY: the buffer was mapped just above.
            unsafe { vaUnmapBuffer(self.display, buffer) };
            return Err(CaptureError::Os(
                "vaMapBuffer returned a null pointer".to_owned(),
            ));
        };
        Ok(VaMapping {
            display: self.display,
            buffer,
            pointer,
            len,
        })
    }

    /// Destroys one buffer, reporting instead of propagating failure.
    fn destroy_buffer(&self, buffer: VaBufferId) -> bool {
        if buffer == VA_INVALID_ID {
            return true;
        }
        // SAFETY: `buffer` was created on this display and is destroyed exactly once, because
        // the caller keeps no further copy of the id.
        let status = unsafe { vaDestroyBuffer(self.display, buffer) };
        status == VA_STATUS_SUCCESS
    }

    /// The picture width this encoder codes, in pixels.
    pub(crate) fn width(&self) -> u32 {
        self.width
    }

    /// The picture height this encoder codes, in pixels.
    pub(crate) fn height(&self) -> u32 {
        self.height
    }
}

impl Drop for Encoder {
    fn drop(&mut self) {
        // SAFETY: every handle below was created on this display and is destroyed once. The
        // order matters only in that the context goes before the config it was created from.
        unsafe {
            if let Some(image) = self.image {
                vaDestroyImage(self.display, image.image_id);
            }
            for buffer in [self.coded_buffer, self.sequence_parameters] {
                if buffer != VA_INVALID_ID {
                    vaDestroyBuffer(self.display, buffer);
                }
            }
            for buffer in self.misc_parameters {
                if buffer != VA_INVALID_ID {
                    vaDestroyBuffer(self.display, buffer);
                }
            }
            if self.context != VA_INVALID_ID {
                vaDestroyContext(self.display, self.context);
            }
            if self.surfaces_created {
                vaDestroySurfaces(
                    self.display,
                    self.surfaces.as_mut_ptr(),
                    self.surfaces.len() as u32,
                );
            }
            if self.config != VA_INVALID_ID {
                vaDestroyConfig(self.display, self.config);
            }
            vaTerminate(self.display);
        }
    }
}

// SAFETY: the encoder is used from the capture thread alone; moving it into that thread at
// construction is the one transfer that happens.
unsafe impl Send for Encoder {}

/// A mapped VAAPI buffer, unmapped when dropped.
struct VaMapping {
    display: VaDisplay,
    buffer: VaBufferId,
    pointer: ptr::NonNull<u8>,
    len: usize,
}

impl VaMapping {
    /// The start of the mapped region.
    fn as_ptr(&self) -> *mut u8 {
        self.pointer.as_ptr()
    }

    /// The mapped region as bytes.
    fn as_mut_slice(&mut self) -> &mut [u8] {
        // SAFETY: `pointer` is the base of a live mapping at least `len` bytes long, and the
        // guard keeps it mapped for as long as the borrow lives.
        unsafe { std::slice::from_raw_parts_mut(self.pointer.as_ptr(), self.len) }
    }
}

impl Drop for VaMapping {
    fn drop(&mut self) {
        // SAFETY: the buffer was mapped by `map_buffer` and is unmapped once.
        unsafe { vaUnmapBuffer(self.display, self.buffer) };
    }
}

