/// The codec a pipeline encodes with.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Codec {
    /// H.264/AVC. The profile is resolved against the driver's entry points.
    H264,
    /// H.265/HEVC, Main profile.
    Hevc,
}

impl Codec {
    /// The VAAPI profile id to configure.
    const fn profile(self, h264_profile: H264Profile) -> i32 {
        match self {
            Self::H264 => h264_profile_id(h264_profile),
            Self::Hevc => VAProfileHEVCMain,
        }
    }

    /// Whether the codec is HEVC, which decides which parameter buffers are built.
    const fn is_hevc(self) -> bool {
        matches!(self, Self::Hevc)
    }
}

/// How many seconds of video one GOP covers.
///
/// The GOP is deliberately short: a client that drops frames recovers at the next IDR, so the
/// interval trades bitrate against recovery time, and two seconds is where the macOS
/// backend's VideoToolbox session also sits.
pub(crate) const GOP_SECONDS: u32 = 2;

