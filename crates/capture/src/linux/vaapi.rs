/// Creates one driver-side buffer, copying `data` (or allocating, when `data` is null).
fn create_buffer(
    display: VaDisplay,
    context: VaContextId,
    kind: u32,
    size: u32,
    data: *mut c_void,
) -> Result<VaBufferId, CaptureError> {
    let mut buffer = VA_INVALID_ID;
    // SAFETY: the context is live, `data` is either null or valid for `size` bytes, and the id
    // is written on success.
    let status = unsafe { vaCreateBuffer(display, context, kind, size, 1, data, &mut buffer) };
    if status != VA_STATUS_SUCCESS {
        return Err(va_error("vaCreateBuffer", status));
    }
    Ok(buffer)
}

/// Builds the H.264 sequence parameters.
fn h264_sequence_parameters(
    settings: &H264Settings,
    bits_per_second: u32,
    gop: u32,
) -> VaEncSequenceParameterH264 {
    // The `seq_fields` union, field by field, in declaration order.
    let mut seq_fields = 0u32;
    let mut field = |shift: u32, width: u32, value: u32| {
        seq_fields |= (value & ((1 << width) - 1)) << shift;
    };
    field(0, 2, 1); // chroma_format_idc: 4:2:0
    field(2, 1, 1); // frame_mbs_only_flag
    field(3, 1, 0); // mb_adaptive_frame_field_flag
    field(4, 1, 0); // seq_scaling_matrix_present_flag
    field(5, 1, 1); // direct_8x8_inference_flag
    field(6, 4, u32::from(settings.log2_max_frame_num_minus4));
    field(10, 2, u32::from(settings.pic_order_cnt_type));
    field(12, 4, u32::from(settings.log2_max_pic_order_cnt_lsb_minus4));
    field(16, 1, 0); // delta_pic_order_always_zero_flag

    // The `vui_fields` union: only the flags the packed SPS sets are set here.
    let has_crop = settings.crop_right() != 0 || settings.crop_bottom() != 0;
    let vui_fields = (1 << 1)      // timing_info_present_flag
        | (1 << 2)               // bitstream_restriction_flag
        | (15 << 3)              // log2_max_mv_length_horizontal
        | (15 << 8)              // log2_max_mv_length_vertical
        | (1 << 13)              // fixed_frame_rate_flag
        | (1 << 15); // motion_vectors_over_pic_boundaries_flag

    VaEncSequenceParameterH264 {
        seq_parameter_set_id: 0,
        level_idc: settings.level_idc,
        intra_period: gop,
        intra_idr_period: gop,
        ip_period: 1,
        bits_per_second,
        max_num_ref_frames: settings.max_num_ref_frames,
        picture_width_in_mbs: settings.mb_width,
        picture_height_in_mbs: settings.mb_height,
        seq_fields,
        bit_depth_luma_minus8: 0,
        bit_depth_chroma_minus8: 0,
        num_ref_frames_in_pic_order_cnt_cycle: 0,
        offset_for_non_ref_pic: 0,
        offset_for_top_to_bottom_field: 0,
        offset_for_ref_frame: [0; 256],
        frame_cropping_flag: u8::from(has_crop),
        frame_crop_left_offset: 0,
        frame_crop_right_offset: settings.crop_right(),
        frame_crop_top_offset: 0,
        frame_crop_bottom_offset: settings.crop_bottom(),
        vui_parameters_present_flag: 1,
        vui_fields,
        aspect_ratio_idc: 0,
        sar_width: 0,
        sar_height: 0,
        num_units_in_tick: 1,
        time_scale: settings.fps.saturating_mul(2),
        reserved: [0; 4],
    }
}

/// Builds the H.264 picture parameters for one frame.
#[allow(clippy::too_many_arguments)]
fn h264_picture_parameters(
    settings: &H264Settings,
    surface: VaSurfaceId,
    reference: VaSurfaceId,
    frame_num: u32,
    pic_order_cnt: i32,
    coded_buffer: VaBufferId,
    keyframe: bool,
    idr_pic_id: u16,
) -> VaEncPictureParameterH264 {
    let mut reference_frames = [VaPictureH264::invalid(); 16];
    if reference != VA_INVALID_ID {
        let previous = previous_frame_num(frame_num);
        reference_frames[0] = VaPictureH264::reference(reference, previous, pic_order_cnt - 1);
    }

    // The `pic_fields` union, mirroring the PPS this encoder writes.
    let mut pic_fields = 0u32;
    let mut field = |shift: u32, width: u32, value: u32| {
        pic_fields |= (value & ((1 << width) - 1)) << shift;
    };
    field(0, 1, u32::from(keyframe)); // idr_pic_flag
    field(1, 2, 1); // reference_pic_flag: every frame is a reference
    field(3, 1, u32::from(settings.entropy_coding)); // entropy_coding_mode_flag
    field(4, 1, 0); // weighted_pred_flag
    field(5, 2, 0); // weighted_bipred_idc
    field(7, 1, 0); // constrained_intra_pred_flag
    field(8, 1, u32::from(settings.transform_8x8)); // transform_8x8_mode_flag
    field(9, 1, 0); // deblocking_filter_control_present_flag
    field(10, 1, 0); // redundant_pic_cnt_present_flag
    field(11, 1, 0); // pic_order_present_flag
    field(12, 1, 0); // pic_scaling_matrix_present_flag
    let _ = idr_pic_id;

    VaEncPictureParameterH264 {
        curr_pic: VaPictureH264 {
            picture_id: surface,
            frame_idx: frame_num,
            flags: 0,
            top_field_order_cnt: pic_order_cnt,
            bottom_field_order_cnt: pic_order_cnt,
            reserved: [0; 4],
        },
        reference_frames,
        coded_buf: coded_buffer,
        pic_parameter_set_id: 0,
        seq_parameter_set_id: 0,
        last_picture: 0,
        frame_num: frame_num as u16,
        pic_init_qp: settings.pic_init_qp_minus26.saturating_add(26).clamp(0, 51) as u8,
        num_ref_idx_l0_active_minus1: 0,
        num_ref_idx_l1_active_minus1: 0,
        chroma_qp_index_offset: 0,
        second_chroma_qp_index_offset: 0,
        pic_fields,
        reserved: [0; 4],
    }
}

