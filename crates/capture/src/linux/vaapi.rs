/// Every DRM render node of the host, in the kernel's own order.
///
/// The nodes are named `renderD<N>`; the numbering is per driver and a machine with two GPUs
/// has two of them, which is why the encoder is tried on each in turn rather than on a fixed
/// path.
pub(crate) fn render_nodes() -> Vec<PathBuf> {
    let mut nodes = Vec::new();
    let Ok(entries) = std::fs::read_dir("/dev/dri") else {
        return nodes;
    };
    for entry in entries.flatten() {
        if entry
            .file_name()
            .to_str()
            .is_some_and(|name| name.starts_with("renderD"))
        {
            nodes.push(entry.path());
        }
    }
    nodes.sort();
    nodes
}

/// Builds an encoder on the first render node that can encode the codec.
///
/// A machine usually has one render node, but a laptop with a discrete GPU has two, and
/// which of them can encode depends on the driver. Trying them in order means the backend
/// works on either without configuration. The last failure is reported, because the first
/// node is often the one without a driver attached and its error would be the misleading one.
pub(crate) fn open_encoder(
    width: u32,
    height: u32,
    fps: u32,
    codec: Codec,
    bitrate_kbps: u32,
) -> Result<Encoder, CaptureError> {
    let nodes = render_nodes();
    if nodes.is_empty() {
        return Err(CaptureError::Os(
            "no DRM render node in /dev/dri, so there is no VAAPI device to encode on"
                .to_owned(),
        ));
    }

    let mut last = None;
    for node in nodes {
        match Encoder::new(&node, width, height, fps, codec, bitrate_kbps) {
            Ok(encoder) => {
                tracing::info!(node = %node.display(), "VAAPI encoder ready");
                return Ok(encoder);
            }
            Err(error) => {
                tracing::warn!(node = %node.display(), %error, "this render node cannot encode");
                last = Some(error);
            }
        }
    }
    Err(last.unwrap_or(CaptureError::UnsupportedParameters))
}

/// Opens one DRM render node for reading and writing.
fn open_render_node(node: &Path) -> Result<OwnedFd, CaptureError> {
    let file = std::fs::OpenOptions::new()
        .read(true)
        .write(true)
        .open(node)
        .map_err(|error| match error.kind() {
            std::io::ErrorKind::PermissionDenied => CaptureError::PermissionDenied,
            _ => CaptureError::Os(format!("could not open {}: {error}", node.display())),
        })?;
    Ok(OwnedFd::from(file))
}

/// Opens a DRM render node as a VAAPI display.
fn display_from_drm(fd: RawFd) -> Result<VaDisplay, CaptureError> {
    // SAFETY: `fd` is an open descriptor; libva duplicates it internally.
    let display = unsafe { vaGetDisplayDRM(fd) };
    if display.is_null() {
        return Err(CaptureError::Os(
            "libva could not create a display from the DRM render node".to_owned(),
        ));
    }
    let mut major = 0;
    let mut minor = 0;
    // SAFETY: the display came from `vaGetDisplayDRM` and both outputs are valid.
    let status = unsafe { vaInitialize(display, &mut major, &mut minor) };
    if status != VA_STATUS_SUCCESS {
        return Err(va_error("vaInitialize", status));
    }
    tracing::debug!(major, minor, "libva initialised");
    Ok(display)
}

/// Picks the most capable H.264 profile the driver offers for slice encoding.
fn supported_h264_profile(display: VaDisplay) -> Result<H264Profile, CaptureError> {
    for profile in [
        H264Profile::High,
        H264Profile::Main,
        H264Profile::ConstrainedBaseline,
    ] {
        if supports_encode(display, h264_profile_id(profile)) {
            return Ok(profile);
        }
    }
    Err(CaptureError::UnsupportedParameters)
}

/// The VAAPI profile id of one H.264 profile.
const fn h264_profile_id(profile: H264Profile) -> i32 {
    match profile {
        H264Profile::High => VAProfileH264High,
        H264Profile::Main => VAProfileH264Main,
        H264Profile::ConstrainedBaseline => VAProfileH264ConstrainedBaseline,
    }
}

/// Whether the driver has a slice-encode entry point for one profile.
fn supports_encode(display: VaDisplay, profile: i32) -> bool {
    let mut entrypoints = [0i32; 16];
    let mut count = 0i32;
    // SAFETY: the display is live and the array is valid for its declared length.
    let status =
        unsafe { vaQueryConfigEntrypoints(display, profile, entrypoints.as_mut_ptr(), &mut count) };
    if status != VA_STATUS_SUCCESS {
        tracing::debug!(profile, "the driver reports no entry points for this profile");
        return false;
    }
    let count = (count.max(0) as usize).min(entrypoints.len());
    let supported = entrypoints[..count].contains(&VAEntrypointEncSlice);
    tracing::debug!(profile, entrypoints = ?&entrypoints[..count], supported);
    supported
}

/// Wraps an operation and a status code into a backend failure, with libva's own message.
fn va_error(operation: &str, status: VaStatus) -> CaptureError {
    CaptureError::Os(format!(
        "{operation} failed: {} ({status})",
        va_error_string(status)
    ))
}

/// libva's description of a status code.
fn va_error_string(status: VaStatus) -> String {
    // SAFETY: `vaErrorStr` returns a static string for any status code.
    let message = unsafe { vaErrorStr(status) };
    if message.is_null() {
        return "unknown libva error".to_owned();
    }
    // SAFETY: the returned pointer is a NUL-terminated static string.
    unsafe { std::ffi::CStr::from_ptr(message) }
        .to_string_lossy()
        .into_owned()
}

