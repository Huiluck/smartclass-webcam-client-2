//! VAAPI encoding: the libva bindings and the encoder built on them.
//!
//! # Why the bindings are hand-written
//!
//! `libva` ships C headers, so the usual way to reach it is through `bindgen` or a C shim.
//! Neither fits here: this crate has to `cargo check` on hosts without `va/va.h` (the macOS
//! and Windows backends must also not grow a build dependency on a Linux-only library), so
//! the functions used below are declared by hand against the documented ABI. Every struct is
//! transcribed field for field, unions of bit fields become one `u32` filled bit by bit, and
//! the sizes are asserted at compile time at the bottom of this file.
//!
//! # What the runtime needs
//!
//! - `libva.so.2` and `libva-drm.so.2` (Debian/Ubuntu: `libva2`, `libva-drm2`) plus a
//!   hardware driver (`intel-media-va-driver`, `mesa-va-drivers`, …). Both libraries are
//!   linked by name; a host without them fails to link, which is the honest failure mode.
//! - A DRM render node (`/dev/dri/renderD128` and friends) the process may open. The node is
//!   the VAAPI display, so no X11 or Wayland session is needed and the client works from a
//!   service or an SSH session.
//! - A hardware H.264 or H.265 *encode* entry point (`VAEntrypointEncSlice`). A decode-only
//!   driver, or a machine without a render node, is rejected while the encoder is built.
//!
//! # The shape of the encoder
//!
//! The stream is a low-delay IPPP stream: one IDR, then P frames, no B frames, no
//! reordering, eight-bit `frame_num` and picture order counts, one reference frame, and a GOP
//! of two seconds. Parameter sets are handed to the driver as packed headers — `SPS || PPS`
//! for H.264, `VPS || SPS || PPS` for H.265 — in front of every IDR, which is what makes each
//! access unit self-contained and lets a client join mid-stream.
//!
//! Two surfaces alternate as "current picture" and "reference", one coded buffer is reused for
//! every frame, and every frame is synchronised and drained before the next one starts, so the
//! pipeline needs no buffer pool. The sequence parameters
//! (`VAEncSequenceParameterBuffer{H264,HEVC}`) and the rate-control parameters are created
//! once and referenced by every picture; picture and slice parameters are created and
//! destroyed per frame, as FFmpeg's VAAPI encoders also do.
//!
//! # Known limitations, none of which this host can test
//!
//! - The *slice* headers are generated by the driver. FFmpeg writes them itself as a further
//!   packed header, which needs a full slice-header syntax writer (CABAC init, reference-list
//!   modification, memory management); that is a second bitstream writer, and every driver
//!   this backend targets generates slice headers when they are not supplied.
//! - Whether a driver produces a stream matching the packed SPS/PPS is unverified without
//!   hardware. The likely failure — a driver without the profile — is caught before the
//!   first frame by querying the entry points.
//! - The frames are uploaded with `vaPutImage`, which costs one driver-side copy. Deriving an
//!   image from the surface would avoid it, but the derived layout may be `I420`/`YV12`
//!   instead of `NV12`, and that would have to be compensated per driver.

