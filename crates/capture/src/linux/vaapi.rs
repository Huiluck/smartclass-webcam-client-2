/// Copies a tightly packed NV12 frame into an NV12 image, honouring the image's pitches.
fn write_nv12(
    destination: &mut [u8],
    image: &VaImage,
    frame: &[u8],
    width: usize,
    height: usize,
) -> Result<(), CaptureError> {
    let luma_len = width * height;
    let luma_pitch = image.pitches[0] as usize;
    let chroma_pitch = image.pitches[1] as usize;
    let luma_base = image.offsets[0] as usize;
    let chroma_base = image.offsets[1] as usize;

    for row in 0..height {
        let target = luma_base + row * luma_pitch;
        destination
            .get_mut(target..target + width)
            .ok_or_else(short_image)?
            .copy_from_slice(
                frame
                    .get(row * width..(row + 1) * width)
                    .ok_or_else(short_frame)?,
            );
    }
    for row in 0..height / 2 {
        let source = luma_len + row * width;
        let target = chroma_base + row * chroma_pitch;
        destination
            .get_mut(target..target + width)
            .ok_or_else(short_image)?
            .copy_from_slice(frame.get(source..source + width).ok_or_else(short_frame)?);
    }
    Ok(())
}

/// Copies a tightly packed NV12 frame into a planar (`I420`/`YV12`) image, splitting the
/// interleaved chroma into two planes.
fn write_i420(
    destination: &mut [u8],
    image: &VaImage,
    frame: &[u8],
    width: usize,
    height: usize,
    swap_chroma: bool,
) -> Result<(), CaptureError> {
    let luma_len = width * height;
    let chroma_width = width / 2;
    // I420 stores U before V, YV12 the other way round.
    let (u_plane, v_plane) = if swap_chroma { (2, 1) } else { (1, 2) };
    let u_base = image.offsets[u_plane] as usize;
    let v_base = image.offsets[v_plane] as usize;
    let u_pitch = image.pitches[u_plane] as usize;
    let v_pitch = image.pitches[v_plane] as usize;
    let luma_pitch = image.pitches[0] as usize;

    for row in 0..height {
        let target = row * luma_pitch;
        destination
            .get_mut(target..target + width)
            .ok_or_else(short_image)?
            .copy_from_slice(
                frame
                    .get(row * width..(row + 1) * width)
                    .ok_or_else(short_frame)?,
            );
    }
    for row in 0..height / 2 {
        let source = luma_len + row * width;
        let pairs = frame
            .get(source..source + chroma_width * 2)
            .ok_or_else(short_frame)?;
        // The two planes are written in two passes: one `&mut` into the destination at a time,
        // which is also what keeps the bounds checks in one place.
        for index in 0..chroma_width {
            let u_index = u_base + row * u_pitch + index;
            *destination.get_mut(u_index).ok_or_else(short_image)? = pairs[index * 2];
        }
        for index in 0..chroma_width {
            let v_index = v_base + row * v_pitch + index;
            *destination.get_mut(v_index).ok_or_else(short_image)? = pairs[index * 2 + 1];
        }
    }
    Ok(())
}

/// The error for an image whose planes do not cover the picture.
fn short_image() -> CaptureError {
    CaptureError::Os("the VAAPI staging image is smaller than the picture".to_owned())
}

/// The error for a frame shorter than its geometry.
fn short_frame() -> CaptureError {
    CaptureError::Os("the captured frame is shorter than its geometry".to_owned())
}

