/// The packed-header description for the parameter-set blob.
fn header_parameter(byte_len: usize) -> VaEncPackedHeaderParameter {
    VaEncPackedHeaderParameter {
        kind: VAEncPackedHeaderSequence,
        // The API counts bits, and the bitstream writer never pads the last byte.
        bit_length: (byte_len as u32) * 8,
        // The parameter sets go out with emulation-prevention bytes already inserted.
        has_emulation_bytes: 1,
        reserved: [0; 4],
    }
}

